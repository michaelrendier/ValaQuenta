#!/usr/bin/env python3
"""build_scad.py -- writes hypergon_frame.scad (the OpenSCAD companion of canvas2d_frame3d.html) from the Python engines, then renders the two PNGs if openscad can.
MODE 0: the n-ball curve in the frame (x = n, y = V, z = S).  MODE 1: the Niemeier gap as bars (x = h mod 16, y = row, z = count).  Run from the repo root with .venv."""
import math, os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "..")))
from ValaQuenta.modules.hypergon_constructibility import maths as hg
from ValaQuenta.modules.bell_curve import maths as bc

pts = [(n / 10, bc.nball_volume(n / 10), bc.nsphere_area(n / 10)) for n in range(1, 161)]
gap = hg.niemeier_gap_theorem()
cnt = [0] * 16
for s in gap["root_systems"]:
    cnt[s["h"] % 16] += 1
ms = [0] * 16
for p in hg.MOONSHINE_PRIMES:
    if p % 2:
        ms[p % 16] += 1
fmt = lambda a: "[" + ",".join(f"[{x:.5f},{y:.5f},{z:.5f}]" for x, y, z in a) + "]"
scad = f"""// SPDX-License-Identifier: GPL-3.0-only
// hypergon_frame.scad -- OpenSCAD companion of canvas2d_frame3d.html; generated by build_scad.py from the ValaQuenta engines
// (hypergon_constructibility 0.200, bell_curve 1.2).  z is up.  MODE 0: the n-ball curve, x = dimension n, y = volume V, z = area S (on the surface z = n*y).
// MODE 1: the Niemeier gap as bars, x = h mod 16, y = row (0 Niemeier root systems, 1 Moonshine primes), z = count.
// Camera: openscad -o out.png -D MODE=0 --camera=8,3,18,60,0,25,95 --projection=o --imgsize=1000,800 hypergon_frame.scad   (canonical poses: skills 'scad-spatial')
MODE = 0;
$fn = 12;
curve = {fmt(pts)};
niemeier = {cnt};       // Niemeier root systems by h mod 16
moonshine = {ms};       // odd Moonshine primes by p mod 16
module axis(v, c, l) {{ color(c) hull() {{ sphere(0.08); translate(v*l) sphere(0.08); }} }}
module frame(bx, by, bz) {{
  color("gray", 0.6) for (a = [[0,0,0],[bx,0,0],[0,by,0],[bx,by,0]]) translate(a) cube([0.04,0.04,bz]);
  color("gray", 0.6) for (a = [[0,0,0],[0,by,0],[0,0,bz],[0,by,bz]]) translate(a) cube([bx,0.04,0.04]);
  color("gray", 0.6) for (a = [[0,0,0],[bx,0,0],[0,0,bz],[bx,0,bz]]) translate(a) cube([0.04,by,0.04]);
  axis([1,0,0], "red", bx); axis([0,1,0], "green", by); axis([0,0,1], "blue", bz);
}}
if (MODE == 0) {{
  frame(16, 6, 36);
  for (i = [1:len(curve)-1]) color([curve[i][0]/16, 0.4, 1 - curve[i][0]/16]) hull() {{ translate(curve[i-1]) sphere(0.12); translate(curve[i]) sphere(0.12); }}
  for (n = [1,2,4,8,16]) color("black") translate([n, PI_V(n), PI_S(n)]) sphere(0.25);
}} else {{
  frame(16, 2, 3);
  for (r = [0:15]) {{
    if (niemeier[r] > 0) color("steelblue") translate([r+0.1, 0.1, 0]) cube([0.8, 0.8, niemeier[r]]);
    if (moonshine[r] > 0) color("darkorange") translate([r+0.1, 1.1, 0]) cube([0.8, 0.8, moonshine[r]]);
  }}
}}
function PI_V(n) = n == 1 ? 2 : n == 2 ? PI : n == 4 ? PI*PI/2 : n == 8 ? pow(PI,4)/24 : pow(PI,8)/40320;
function PI_S(n) = n * PI_V(n);
"""
open(os.path.join(HERE, "hypergon_frame.scad"), "w", encoding="utf-8").write(scad)
for mode, name, cam in ((0, "A", "8,3,18,60,0,25,95"), (1, "B", "8,1,1.5,60,0,25,32")):
    out = os.path.join(HERE, f"hypergon_frame_{name}.png")
    for cmd in (["xvfb-run", "-a", "openscad"], ["openscad"]):
        try:
            r = subprocess.run(cmd + ["-o", out, "-D", f"MODE={mode}", f"--camera={cam}", "--projection=o", "--imgsize=1000,800", "--colorscheme=Tomorrow", os.path.join(HERE, "hypergon_frame.scad")],
                               capture_output=True, text=True, timeout=240)
            if os.path.exists(out) and r.returncode == 0:
                print("rendered", out); break
        except Exception as e:
            print(cmd[0], "failed:", e)
    else:
        print("no render for", name, (r.stderr or "")[-300:])
