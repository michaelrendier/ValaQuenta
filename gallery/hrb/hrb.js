/* hrb.js -- canvas-2D charts for the H_RB gallery. No libraries. Reads CSS tokens so both themes contrast.
   Data: window.HRB (data/hrb_data.js, generated by experiments.py from the engines). */
(function () {
  const css = (n) => getComputedStyle(document.documentElement).getPropertyValue(n).trim();
  const PAL = ['--c1', '--c2', '--c3', '--c4', '--c5', '--c6'];
  const redraws = [], byId = {};
  function reg(cv, run) { const k = cv.id || ('cv' + redraws.length); if (byId[k] !== undefined) redraws[byId[k]] = run; else { byId[k] = redraws.length; redraws.push(run); } }
  function setup(cv, aspect) {
    const dpr = window.devicePixelRatio || 1, w = cv.parentElement.clientWidth || 800;
    cv.style.width = w + 'px'; cv.style.height = (w * aspect) + 'px';
    cv.width = Math.round(w * dpr); cv.height = Math.round(w * aspect * dpr);
    const g = cv.getContext('2d'); g.setTransform(dpr, 0, 0, dpr, 0, 0);
    return { g, W: w, H: w * aspect };
  }
  function nice(lo, hi, n) {
    const span = hi - lo || 1, step0 = span / n, mag = Math.pow(10, Math.floor(Math.log10(step0)));
    const f = step0 / mag, step = (f < 1.5 ? 1 : f < 3 ? 2 : f < 7 ? 5 : 10) * mag, out = [];
    for (let v = Math.ceil(lo / step) * step; v <= hi + 1e-12; v += step) out.push(+v.toPrecision(12));
    return out;
  }
  function frame(o) {
    const { g, W, H } = setup(o.cv, o.aspect || 0.5), m = { l: 62, r: 18, t: 30, b: 46 };
    g.fillStyle = css('--card'); g.fillRect(0, 0, W, H);
    const lx = !!o.logx, ly = !!o.logy, fx = lx ? Math.log10 : (v) => v, fy = ly ? Math.log10 : (v) => v;
    const x0 = fx(o.xmin), x1 = fx(o.xmax), y0 = fy(o.ymin), y1 = fy(o.ymax);
    const px = (v) => m.l + (fx(v) - x0) / (x1 - x0) * (W - m.l - m.r), py = (v) => H - m.b - (fy(v) - y0) / (y1 - y0) * (H - m.t - m.b);
    g.strokeStyle = css('--line'); g.fillStyle = css('--mut'); g.font = '12px system-ui,sans-serif'; g.lineWidth = 1;
    const xt = lx ? nice(x0, x1, 8).map((e) => Math.pow(10, e)) : nice(o.xmin, o.xmax, 8), yt = ly ? nice(y0, y1, 6).map((e) => Math.pow(10, e)) : nice(o.ymin, o.ymax, 6);
    const fmt = (v) => (Math.abs(v) >= 1e4 || (Math.abs(v) < 1e-3 && v !== 0)) ? v.toExponential(0) : +v.toPrecision(4);
    g.textAlign = 'center'; (o.noxt ? [] : xt).forEach((v) => { const x = px(v); g.beginPath(); g.moveTo(x, m.t); g.lineTo(x, H - m.b); g.stroke(); g.fillText(fmt(v), x, H - m.b + 16); });
    g.textAlign = 'right'; yt.forEach((v) => { const y = py(v); g.beginPath(); g.moveTo(m.l, y); g.lineTo(W - m.r, y); g.stroke(); g.fillText(fmt(v), m.l - 6, y + 4); });
    g.strokeStyle = css('--fg'); g.strokeRect(m.l, m.t, W - m.l - m.r, H - m.t - m.b);
    g.fillStyle = css('--fg'); g.textAlign = 'center'; g.font = '13px system-ui,sans-serif';
    if (o.xlabel) g.fillText(o.xlabel, (m.l + W - m.r) / 2, H - 8);
    if (o.title) { g.textAlign = 'left'; g.fillText(o.title, m.l, 18); }
    if (o.ylabel) { g.save(); g.translate(14, (m.t + H - m.b) / 2); g.rotate(-Math.PI / 2); g.textAlign = 'center'; g.fillText(o.ylabel, 0, 0); g.restore(); }
    return { g, W, H, m, px, py, fx, fy };
  }
  function legend(F, names, x, y) {
    const g = F.g; g.font = '12px system-ui,sans-serif'; g.textAlign = 'left';
    names.forEach((n, i) => { g.fillStyle = css(PAL[i % 6]); g.fillRect(x, y + i * 16 - 8, 14, 3); g.fillStyle = css('--fg'); g.fillText(n, x + 20, y + i * 16 - 2); });
  }
  function vline(F, v, label, colour) {
    const x = F.px(v); if (!isFinite(x)) return; F.g.save(); F.g.setLineDash([5, 4]); F.g.strokeStyle = css(colour || '--acc'); F.g.beginPath(); F.g.moveTo(x, F.m.t); F.g.lineTo(x, F.H - F.m.b); F.g.stroke(); F.g.restore();
    if (label) { F.g.fillStyle = css(colour || '--acc'); F.g.textAlign = 'left'; F.g.fillText(label, x + 4, F.m.t + 12); }
  }
  function hline(F, v, label, colour) {
    const y = F.py(v); F.g.save(); F.g.setLineDash([5, 4]); F.g.strokeStyle = css(colour || '--acc'); F.g.beginPath(); F.g.moveTo(F.m.l, y); F.g.lineTo(F.W - F.m.r, y); F.g.stroke(); F.g.restore();
    if (label) { F.g.fillStyle = css(colour || '--acc'); F.g.textAlign = 'right'; F.g.fillText(label, F.W - F.m.r - 4, y - 4); }
  }
  /* line chart: series = [{name, x:[], y:[], dash?}] */
  function lines(cv, series, o) {
    const run = () => {
      const all = series.flatMap((s) => s.y.filter(isFinite)), allx = series.flatMap((s) => s.x);
      const op = Object.assign({ cv, xmin: Math.min(...allx), xmax: Math.max(...allx), ymin: Math.min(...all), ymax: Math.max(...all) }, o);
      if (!o.ymin && o.ymin !== 0) { const pad = (op.ymax - op.ymin) * 0.06 || 1; op.ymin -= op.logy ? 0 : pad; op.ymax += op.logy ? 0 : pad; }
      const F = frame(op);
      series.forEach((s, i) => { F.g.strokeStyle = css(s.colour || PAL[i % 6]); F.g.lineWidth = 2; F.g.setLineDash(s.dash || []); F.g.beginPath(); let on = false;
        s.x.forEach((xv, k) => { const yv = s.y[k]; if (!isFinite(yv) || (op.logy && yv <= 0)) { on = false; return; } const X = F.px(xv), Y = F.py(yv); if (!on) { F.g.moveTo(X, Y); on = true; } else F.g.lineTo(X, Y); }); F.g.stroke(); F.g.setLineDash([]); });
      if (o.legend !== false && series.length > 1) legend(F, series.map((s) => s.name), F.m.l + 10, F.m.t + 18);
      if (o.after) o.after(F);
    };
    run(); reg(cv, run);
  }
  /* heatmap: z[i][j], i = rows (y), j = cols (x); div:true = diverging (blue-white-red) about 0. Drawn through ImageData so 500x500 grids are fast. */
  function hsl2rgb(h, s, l) { h /= 360; const a = s * Math.min(l, 1 - l), f = (n) => { const k = (n + h * 12) % 12; return l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)); }; return [f(0) * 255, f(8) * 255, f(4) * 255]; }
  function heat(cv, z, o) {
    const run = () => {
      const ny = z.length, nx = z[0].length, op = Object.assign({ cv, aspect: 0.6 }, o), F = frame(op);
      let lo = o.zmin, hi = o.zmax; if (lo === undefined || hi === undefined) { lo = Infinity; hi = -Infinity; for (const r of z) for (const v of r) { if (isFinite(v)) { if (v < lo) lo = v; if (v > hi) hi = v; } } }
      const dv = !!o.div, m = Math.max(Math.abs(lo), Math.abs(hi));
      const rgb = (v) => { let t = dv ? (v / m + 1) / 2 : (v - lo) / (hi - lo || 1); t = Math.min(1, Math.max(0, t));
        if (dv) { const r = t < .5 ? 40 + 430 * t : 255, b = t > .5 ? 40 + 430 * (1 - t) : 255, gg = 255 - Math.abs(t - .5) * 2 * 215; return [r, gg, b]; }
        return hsl2rgb(250 - 250 * t, .85, .22 + .38 * t); };
      const off = document.createElement('canvas'); off.width = nx; off.height = ny; const og = off.getContext('2d'), im = og.createImageData(nx, ny);
      for (let i = 0; i < ny; i++) for (let j = 0; j < nx; j++) { const c = rgb(z[i][j]), k = ((ny - 1 - i) * nx + j) * 4; im.data[k] = c[0]; im.data[k + 1] = c[1]; im.data[k + 2] = c[2]; im.data[k + 3] = 255; }
      og.putImageData(im, 0, 0); F.g.imageSmoothingEnabled = false; F.g.drawImage(off, F.m.l, F.m.t, F.W - F.m.l - F.m.r, F.H - F.m.t - F.m.b);
      F.g.strokeStyle = css('--fg'); F.g.strokeRect(F.m.l, F.m.t, F.W - F.m.l - F.m.r, F.H - F.m.t - F.m.b);
      if (o.after) o.after(F);
      const bar = document.createElement('div'); bar.className = 'cbar'; bar.textContent = `colour: ${dv ? '±' + m.toPrecision(3) : lo.toPrecision(3) + ' … ' + hi.toPrecision(3)}`;
      const old = cv.parentElement.querySelector('.cbar'); if (old) old.remove(); cv.parentElement.appendChild(bar);
    };
    run(); reg(cv, run);
  }
  /* categorical bars: items = [{label, v, colour?}] */
  function bars(cv, items, o) {
    const run = () => {
      const lo = Math.min(0, ...items.map((i) => i.v)), hi = Math.max(...items.map((i) => i.v)) * 1.08 || 1;
      const F = frame(Object.assign({ cv, xmin: 0, xmax: items.length, ymin: lo, ymax: hi, aspect: 0.5, noxt: true }, o)), bw = (F.W - F.m.l - F.m.r) / items.length;
      items.forEach((it, i) => { F.g.fillStyle = css(it.colour || PAL[i % 6]); const y = F.py(it.v), y0 = F.py(0); F.g.fillRect(F.m.l + i * bw + bw * 0.15, Math.min(y, y0), bw * 0.7, Math.abs(y0 - y));
        F.g.fillStyle = css('--fg'); F.g.textAlign = 'center'; F.g.font = '11px system-ui,sans-serif'; F.g.fillText(it.label, F.m.l + i * bw + bw / 2, F.H - F.m.b + 15); F.g.fillText(+it.v.toPrecision(4), F.m.l + i * bw + bw / 2, Math.min(y, y0) - 4); });
    };
    run(); reg(cv, run);
  }
  function table(el, head, rows) {
    el.innerHTML = '<table><thead><tr>' + head.map((h) => `<th>${h}</th>`).join('') + '</tr></thead><tbody>' + rows.map((r) => '<tr>' + r.map((c) => `<td>${c}</td>`).join('') + '</tr>').join('') + '</tbody></table>';
  }
  const redrawAll = () => redraws.forEach((f) => f());
  window.addEventListener('resize', redrawAll);
  if (window.matchMedia) window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', () => setTimeout(redrawAll, 30));
  window.HRBLIB = { lines, heat, bars, table, vline, hline, redrawAll, css };
  window.hrbTheme = function (t) { document.documentElement.setAttribute('data-theme', t); setTimeout(redrawAll, 30); };
})();
