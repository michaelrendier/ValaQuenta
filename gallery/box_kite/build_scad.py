#!/usr/bin/env python3
"""build_scad.py -- writes box_kite_octahedron.scad (the printable OpenSCAD companion of canvas2d_octahedron.html) from the Python engine (box_kite 0.4),
then renders the PNGs and the STL if openscad can.  STRUT picks the box-kite (1..7); every strut's six labels are in the file.
MODE 0: the printable object (spheres, struts, label plates, one colour).  MODE 1: the display model (axes coloured as on the web page, labelled x/y/z gnomon, bounding box).
Run from the repo root with .venv:  python3 ValaQuenta/gallery/box_kite/build_scad.py"""
import os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "..")))
from ValaQuenta.modules.box_kite import maths as bk

lab, ax = [], []
for s in range(1, 8):
    g = bk.box_kite_graph(s)
    V = g["vertices"]
    # axis k carries the k-th reversal pair; first member at +, second at - (the same rule as bk.js octCoords)
    pos = []
    for i, v in enumerate(V):
        k = next(k for k, e in enumerate(g["non_edges"]) if i in e)
        pos.append((k, 1 if g["non_edges"][k][0] == i else -1))
    lab.append([f'"{v[0]},{v[1] + 8}"' for v in V])
    ax.append([[k, sg] for k, sg in pos])
labs = "[" + ",\n  ".join("[" + ",".join(l) + "]" for l in lab) + "]"
axs = "[" + ",\n  ".join(str(a).replace(" ", "") for a in ax) + "]"
edges = [bk.box_kite_graph(s)["edges"] for s in range(1, 8)]
eds = "[" + ",\n  ".join(str([list(e) for e in E]).replace(" ", "") for E in edges) + "]"
scad = f"""// SPDX-License-Identifier: GPL-3.0-only
// box_kite_octahedron.scad -- OpenSCAD companion of canvas2d_octahedron.html; generated by build_scad.py from the ValaQuenta engine (box_kite 0.4).  z is up.
// One box-kite (strut STRUT, 1..7): six assessors as spheres on +-x, +-y, +-z, twelve struts between them (the vanishing products), a label plate on each vertex
// reading "a,b+8" (the assessor (a,b) = plane span(e_a, e_(b+8))).  The three reversal pairs (the only non-adjacent vertex pairs) are the three axes.
// MODE 0: printable, one colour.  MODE 1: display: axes coloured red/green/blue as on the web page, labelled gnomon, bounding box (the scale reference).
// Camera: openscad -o out.png -D STRUT=1 -D MODE=1 --camera=-8,0,-8,60,0,25,300 --projection=o --imgsize=1000,800 box_kite_octahedron.scad   (canonical poses: skills 'scad-spatial')
// Print: openscad -o box_kite_1.stl -D STRUT=1 -D MODE=0 box_kite_octahedron.scad     (about 70 mm across at R = 25; text 1.2 mm raised on a 2 mm plate)
STRUT = 1;
MODE = 1;
R = 25;                 // distance of each vertex from the centre (mm)
$fn = 32;
labels = {labs};
axes = {axs};           // per kite, per vertex: [axis index 0..2, sign +1/-1]
edges = {eds};          // per kite: the 12 vertex pairs
colors = ["#d9534f", "#3fa56b", "#4a8fe0"];
function vpos(s, i) = axes[s-1][i][1] * R * [for (c = [0:2]) c == axes[s-1][i][0] ? 1 : 0];
module bar(a, b, r) {{ hull() {{ translate(a) sphere(r); translate(b) sphere(r); }} }}
// rotation that turns the label plane (normal +z, text up +y) to face outward along axis k, sign sg, with text up = +z (or +y on the z axis)
function facing(k, sg) = k == 0 ? [90, 0, sg * 90] : k == 1 ? [90, 0, sg > 0 ? 180 : 0] : [sg > 0 ? 0 : 180, 0, 0];
module plate(s, i, colored) {{            // a disc outside the vertex, facing outward along its axis, carrying the label
  k = axes[s-1][i][0]; sg = axes[s-1][i][1];
  translate(vpos(s, i)) rotate(facing(k, sg)) translate([0, 0, 5]) {{
    cylinder(r = 9, h = 2);
    color(colored ? "#111111" : "white") translate([0, 0, 2]) linear_extrude(1.2) text(labels[s-1][i], size = 5, halign = "center", valign = "center");
  }}
}}
module kite(s, colored) {{
  for (i = [0:5]) {{
    color(colored ? colors[axes[s-1][i][0]] : "white") translate(vpos(s, i)) sphere(5);
    color(colored ? colors[axes[s-1][i][0]] : "white") plate(s, i, colored);
  }}
  for (e = edges[s-1]) color(colored ? "gray" : "white") bar(vpos(s, e[0]), vpos(s, e[1]), 1.6);
}}
module gnomon() {{              // a scale reference placed off the model, in the corner (the octahedron's own axes are x, y, z)
  translate([-1.9 * R, -1.9 * R, -1.9 * R]) for (k = [0:2]) color(colors[k]) {{
    d = [for (c = [0:2]) c == k ? 1 : 0];
    bar([0,0,0], 0.8 * R * d, 0.7);
    translate(0.95 * R * d + [0, 0, k == 2 ? 0 : 0]) rotate([90, 0, 0]) linear_extrude(0.6) text(["x","y","z"][k], size = 5, halign = "center", valign = "center");
  }}
}}
module bbox(h) {{ color("gray", 0.4) difference() {{ cube(2*h, center = true); cube(2*h - 0.8, center = true); }} }}
kite(STRUT, MODE == 1);
if (MODE == 1) {{ gnomon(); }}
"""
open(os.path.join(HERE, "box_kite_octahedron.scad"), "w", encoding="utf-8").write(scad)
print("scad written")
if "--render" in sys.argv:
    out = HERE
    cams = {"A": "-8,0,-8,60,0,25,300"}
    for tag, cam in cams.items():
        subprocess.run(["openscad", "-o", os.path.join(out, f"box_kite_octahedron_{tag}.png"), "-D", "STRUT=1", "-D", "MODE=1", f"--camera={cam}", "--projection=o", "--imgsize=1000,800", "--colorscheme=Tomorrow", os.path.join(HERE, "box_kite_octahedron.scad")], check=True, capture_output=True)
    subprocess.run(["openscad", "-o", os.path.join(out, "box_kite_1.stl"), "-D", "STRUT=1", "-D", "MODE=0", os.path.join(HERE, "box_kite_octahedron.scad")], check=True, capture_output=True)
    print("rendered PNGs and STL")
